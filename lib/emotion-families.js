// 反向索引：一个词只归一个家族。先到先得，撞车不覆盖（测试会守住）。
export const TERM_FAMILY = new Map();
export const DUPLICATE_TERMS = [];
for (const [family, words] of Object.entries(EMOTION_FAMILIES)) {
  for (const word of words) {
    if (TERM_FAMILY.has(word)) {
      DUPLICATE_TERMS.push(`${word}(${TERM_FAMILY.get(word)}/${family})`);
      continue;
    }
    TERM_FAMILY.set(word, family);
  }
}

/** 嘲讽/怼人系：这些家族的图，在诚恳语境里不该出现。 */
export const MOCK_FAMILIES = new Set(['嘲讽', '嫌弃']);

/** 诚恳语境：查询落在这里时，嘲讽图扣分。 */
export const SINCERE_FAMILIES = new Set(['歉意', '感谢', '安慰', '鼓励', '夸奖', '认真', '关心', '谨慎']);

/** 嘲讽图在诚恳查询下的扣分。足够把家族命中(+4)打成负分，直接出局。 */
export const MOCK_PENALTY = 12;

/** 精确查族（词必须整条命中）。 */
export function familyOf(term) {
  const t = String(term ?? '').trim();
  return t ? (TERM_FAMILY.get(t) || '') : '';
}

/**
 * 宽松查族：整条没命中时，用最长子串匹配已知家族词，覆盖「被信任的欣慰」「心疼又无奈」这类长短语。
 * 取最长命中，避免短词抢先。最短 2 字，单字不进自由文本里乱撞。
 */
export function familyOfLoose(term) {
  const t = String(term ?? '').trim();
  if (!t) return '';
  const exact = TERM_FAMILY.get(t);
  if (exact) return exact;
  if (t.length < 2) return '';
  let bestWord = '';
  let bestFamily = '';
  for (const [word, family] of TERM_FAMILY) {
    if (word.length < 2) continue;
    if (t.includes(word) && word.length > bestWord.length) {
      bestWord = word;
      bestFamily = family;
    }
  }
  return bestFamily;
}

/** 一组情绪词（单字符串或数组）覆盖到的家族集合。 */
export function familiesOfEmotion(emotion) {
  const list = Array.isArray(emotion) ? emotion : (emotion ? [emotion] : []);
  const out = new Set();
  for (const item of list) {
    // 允许传「开心,搞笑」这种逗号串：拆开逐个查
    for (const piece of String(item).split(/[,，、\/]/)) {
      const f = familyOfLoose(piece);
      if (f) out.add(f);
    }
  }
  return [...out];
}

/** 家族里的全部词，供向量兜底时判断「图的标签是否落在同类里」。 */
export function termsOfFamilies(families) {
  const set = new Set();
  for (const f of families) {
    for (const w of (EMOTION_FAMILIES[f] || [])) set.add(w);
  }
  return set;
}

